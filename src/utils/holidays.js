/**
 * 주어진 날짜(YYYY-MM-DD)의 한국 공휴일 정보 반환
 * @param {string} dateStr 'YYYY-MM-DD'
 * @returns {{ name: string, isHoliday: true } | null}
 */
export function getKoreanHoliday(dateStr) {
  if (!dateStr || typeof dateStr !== 'string') return null;

  // 1. 변동/대체공휴일 우선 체크
  if (DYNAMIC_HOLIDAYS[dateStr]) {
    return {
      name: DYNAMIC_HOLIDAYS[dateStr],
      isHoliday: true,
    };
  }

  // 2. 고정 양력 공휴일 체크
  const monthDay = dateStr.slice(5); // 'MM-DD'
  if (FIXED_ANNUAL_HOLIDAYS[monthDay]) {
    return {
      name: FIXED_ANNUAL_HOLIDAYS[monthDay],
      isHoliday: true,
    };
  }

  return null;
}
